/* ─── Zone resolver ──────────────────────────────────────────────────────── */

function normalise(s: string): string {
  return s
    .toLowerCase()
    .replace(/^(daerah|mukim|bandar|kawasan|wilayah)\s+/g, '')
    .trim()
}

export function resolveZone(district: string, state?: string): string {
  const d = normalise(district)

  // Exact match first
  if (DISTRICT_ZONE[d]) return DISTRICT_ZONE[d]!

  // Partial match (e.g. "petaling jaya" matches "petaling")
  for (const [key, zone] of Object.entries(DISTRICT_ZONE)) {
    if (d.includes(key) || key.includes(d)) return zone
  }

  // Fall back to state
  if (state) {
    const s = normalise(state)
    if (STATE_ZONE[s]) return STATE_ZONE[s]!
    for (const [key, zone] of Object.entries(STATE_ZONE)) {
      if (s.includes(key) || key.includes(s)) return zone
    }
  }

  return 'WLY01' // final default
}
